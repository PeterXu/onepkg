package installer

import (
	"fmt"
	"strings"
)

// PowerShellRunnerConfig configures the generated run.ps1 script.
type PowerShellRunnerConfig struct {
	Name         string
	Version      string
	Platform     string
	ExpectedArch string // AMD64 or ARM64
	RequireAdmin bool
	HasPayload   bool // emit extraction block iff true
	Commands     []CommandSpec
}

// CommandSpec is one command for run.ps1. Exactly one of Exec or Shell is set.
type CommandSpec struct {
	Exec  string // non-empty -> run bundled file
	Args  []string
	Shell string // non-empty -> run PowerShell expression
}

// GeneratePowerShellRunner produces a lean run.ps1 that runs the configured
// commands once, in order, fail-fast. It reuses the shared CheckAdmin/CheckArch/
// arch-var helpers and declares the -InstallDir/-Action params the (unchanged)
// stub forwards, ignoring them.
func GeneratePowerShellRunner(cfg PowerShellRunnerConfig) (string, error) {
	var b strings.Builder

	fmt.Fprintf(&b, "# %s %s run-commands package for %s\n", cfg.Name, cfg.Version, cfg.Platform)
	b.WriteString("# Generated by onepkg\n\n")

	b.WriteString("param(\n")
	b.WriteString("    [string]$PayloadDir = '',\n")
	b.WriteString("    [string]$InstallDir = '',    # accepted for stub parity; ignored in run mode\n")
	b.WriteString("    [string]$Action = 'install'  # accepted for stub parity; ignored in run mode\n")
	b.WriteString(")\n\n")

	fmt.Fprintf(&b, "$PKG_NAME = %s\n", psQuote(cfg.Name))
	fmt.Fprintf(&b, "$PKG_VERSION = %s\n", psQuote(cfg.Version))
	fmt.Fprintf(&b, "$PKG_PLATFORM = %s\n", psQuote(cfg.Platform))
	b.WriteString(powershellArchVars(cfg.ExpectedArch))
	b.WriteString("\n")

	// Windows known-folder definitions: only variables referenced by the commands
	// (via {dst.Name} in shell or args).
	var kfNames []string
	for _, cmd := range cfg.Commands {
		if cmd.Shell != "" {
			kfNames = append(kfNames, KnownFolderMarkers(cmd.Shell)...)
		}
		for _, a := range cmd.Args {
			kfNames = append(kfNames, KnownFolderMarkers(a)...)
		}
	}
	b.WriteString(EmitKnownFolderDefs(kfNames))

	if cfg.RequireAdmin {
		b.WriteString(powershellCheckAdmin())
	}
	b.WriteString(powershellCheckArch())

	b.WriteString("if ($PayloadDir -eq '') { $PayloadDir = $PSScriptRoot }\n")
	if cfg.RequireAdmin {
		b.WriteString("CheckAdmin\n")
	}
	b.WriteString("CheckArch\n")
	b.WriteString("\n")
	b.WriteString("Push-Location $PayloadDir\n")
	b.WriteString("try {\n")
	if cfg.HasPayload {
		b.WriteString("    Expand-Archive -Path (Join-Path $PayloadDir 'payload.zip') -DestinationPath $PayloadDir -Force\n")
	}
	b.WriteString("    $results = @()\n")
	b.WriteString("    $failures = 0\n")
	fmt.Fprintf(&b, "    Write-Host 'Running %d command(s) for %s %s'\n", len(cfg.Commands), cfg.Name, cfg.Version)
	for _, cmd := range cfg.Commands {
		b.WriteString(runnerCommandBlock(cmd))
	}
	// Results dialog: one line per command + tally. ASCII markers and an ASCII
	// hyphen in the title — run.ps1 is BOM-less UTF-8 and PowerShell 5.1 would
	// misread non-ASCII bytes. [Environment]::NewLine avoids backtick escaping.
	b.WriteString("    Add-Type -AssemblyName System.Windows.Forms\n")
	b.WriteString("    $nl = [Environment]::NewLine\n")
	b.WriteString("    $tally = ('{0} of {1} commands succeeded.' -f ($results.Count - $failures), $results.Count)\n")
	b.WriteString("    $message = ($results -join $nl) + $nl + $nl + $tally\n")
	title := psQuote(cfg.Name + " " + cfg.Version + " - run results")
	b.WriteString("    if ($failures -eq 0) {\n")
	b.WriteString("        $icon = [System.Windows.Forms.MessageBoxIcon]::Information\n")
	b.WriteString("    } else {\n")
	b.WriteString("        $icon = [System.Windows.Forms.MessageBoxIcon]::Warning\n")
	b.WriteString("    }\n")
	b.WriteString("    [System.Windows.Forms.MessageBox]::Show($message, " + title + ", [System.Windows.Forms.MessageBoxButtons]::OK, $icon) | Out-Null\n")
	b.WriteString("    if ($failures -gt 0) { exit 1 } else { exit 0 }\n")
	b.WriteString("} finally {\n")
	b.WriteString("    Pop-Location\n")
	b.WriteString("}\n")

	return b.String(), nil
}

// argPS renders a command argument for inline PowerShell use. Bare values are
// single-quoted (identical to psQuote); marked values become a parenthesized
// concatenation so they are a single token in the log line and the invocation.
func argPS(a string) string {
	e := EmitPathExpr(a)
	if strings.Contains(e, " + ") {
		return "(" + e + ")"
	}
	return e
}

// commandLabel returns the human-readable form of a command for the results
// dialog: exec plus its args space-joined, or the shell expression.
func commandLabel(cmd CommandSpec) string {
	if cmd.Exec != "" {
		parts := append([]string{cmd.Exec}, cmd.Args...)
		return strings.Join(parts, " ")
	}
	return cmd.Shell
}

// runnerCommandBlock renders one command's real-time log line, invocation, and
// result recording. Execution is run-all: a failure is recorded into $results
// and bumps $failures instead of aborting.
func runnerCommandBlock(cmd CommandSpec) string {
	var b strings.Builder
	label := psQuote(commandLabel(cmd))
	if cmd.Exec != "" {
		// Log: Write-Host 'Running:' '<exec>' '<arg>' ...  (all single-quoted via psQuote)
		b.WriteString("    Write-Host 'Running:'")
		b.WriteString(" " + psQuote(cmd.Exec))
		for _, a := range cmd.Args {
			b.WriteString(" " + argPS(a))
		}
		b.WriteString("\n")

		b.WriteString("    $LASTEXITCODE = 0\n")
		b.WriteString("    & (Join-Path $PayloadDir " + psQuote(cmd.Exec) + ")")
		for _, a := range cmd.Args {
			b.WriteString(" " + argPS(a))
		}
		b.WriteString("\n")
	} else {
		b.WriteString("    Write-Host 'Running:' " + psQuote(ReplaceMarkers(cmd.Shell)) + "\n")
		b.WriteString("    $LASTEXITCODE = 0\n")
		b.WriteString("    Invoke-Expression " + psQuote(ReplaceMarkers(cmd.Shell)) + "\n")
	}
	// Record result (run-all, no fail-fast). Exit code is shown only when non-zero,
	// so a failed cmdlet (which leaves $LASTEXITCODE at 0) does not read "(exit 0)".
	b.WriteString("    if ((-not $?) -or ($LASTEXITCODE -ne 0)) {\n")
	b.WriteString("        $results += '[FAIL] ' + " + label + " + $(if ($LASTEXITCODE -ne 0) { ' (exit ' + $LASTEXITCODE + ')' })\n")
	b.WriteString("        $failures++\n")
	b.WriteString("    } else {\n")
	b.WriteString("        $results += '[OK]  ' + " + label + "\n")
	b.WriteString("    }\n")
	return b.String()
}
